var DEFAULT_MAX_BYTES = 26214400;
var DEFAULT_TIMEOUT_MS = 3e4;
async function runWasm(input) {
  const hostFunctions = {
    fetch_relay: async (sourceUrl, sourceHeadersJson, destUrl, destMethod, destHeadersJson, optionsJson) => {
      let maxBytes = DEFAULT_MAX_BYTES;
      let timeoutMs = DEFAULT_TIMEOUT_MS;
      try {
        const opts = optionsJson ? JSON.parse(optionsJson) : {};
        if (typeof opts.max_bytes === "number" && opts.max_bytes > 0) maxBytes = opts.max_bytes;
        if (typeof opts.timeout_ms === "number" && opts.timeout_ms > 0) timeoutMs = opts.timeout_ms;
      } catch {
      }
      const sourceHeaders = {};
      if (sourceHeadersJson) {
        try {
          const parsed = JSON.parse(sourceHeadersJson);
          if (parsed && typeof parsed === "object") {
            for (const [k, v] of Object.entries(parsed)) {
              if (typeof v === "string") sourceHeaders[k] = v;
            }
          }
        } catch {
        }
      }
      const headers = {};
      if (destHeadersJson) {
        try {
          const parsed = JSON.parse(destHeadersJson);
          if (parsed && typeof parsed === "object") {
            for (const [k, v] of Object.entries(parsed)) {
              if (typeof v === "string") headers[k] = v;
            }
          }
        } catch {
        }
      }
      const controller = new AbortController();
      let abortReason = null;
      const timer = setTimeout(() => {
        abortReason = "timeout";
        controller.abort();
      }, timeoutMs);
      try {
        const srcRes = await fetch(sourceUrl, {
          headers: Object.keys(sourceHeaders).length > 0 ? sourceHeaders : void 0,
          signal: controller.signal
        });
        if (!srcRes.ok) {
          const text = await srcRes.text();
          return JSON.stringify({
            error: `source fetch failed: HTTP ${srcRes.status}`,
            status: srcRes.status,
            body: text
          });
        }
        if (!headers["Content-Type"] && !headers["content-type"]) {
          const ct = srcRes.headers.get("content-type");
          if (ct) headers["Content-Type"] = ct;
        }
        let seen = 0;
        let body = srcRes.body;
        if (body) {
          const counter = new TransformStream({
            transform(chunk, ctrl) {
              seen += chunk.byteLength;
              if (seen > maxBytes) {
                abortReason = "size_exceeded";
                controller.abort();
                ctrl.error(new Error("size_exceeded"));
                return;
              }
              ctrl.enqueue(chunk);
            }
          });
          body = body.pipeThrough(counter);
        }
        const destRes = await fetch(destUrl, {
          method: destMethod || "PUT",
          headers,
          body,
          // @ts-expect-error duplex 是串流 request body 在部分 runtime 需要的旗標
          duplex: "half",
          signal: controller.signal
        });
        const destText = await destRes.text();
        if (!destRes.ok) {
          return JSON.stringify({ error: `HTTP ${destRes.status}`, status: destRes.status, body: destText });
        }
        return JSON.stringify({ status: destRes.status, body: destText });
      } catch (e) {
        if (abortReason === "size_exceeded") {
          return JSON.stringify({
            error: "size_exceeded",
            status: 0,
            body: `\u8F49\u767C\u5167\u5BB9\u8D85\u904E max_bytes=${maxBytes}\uFF0C\u5DF2\u4E2D\u6B62`
          });
        }
        if (abortReason === "timeout") {
          return JSON.stringify({
            error: "timeout",
            status: 0,
            body: `\u8D85\u904E timeout_ms=${timeoutMs}\uFF0C\u5DF2\u4E2D\u6B62`
          });
        }
        const errDetail = e instanceof Error ? e.message : String(e);
        return JSON.stringify({ error: `fetch failed: ${errDetail}`, status: 0, body: "" });
      } finally {
        clearTimeout(timer);
      }
    }
  };
  const shim = createWasiShim(JSON.stringify(input), hostFunctions);
  const instance = await WebAssembly.instantiate(
    componentWasm,
    shim.imports
  );
  shim.setMemory(instance.exports.memory);
  await shim.run(instance);
  const stdout = shim.getStdout().trim();
  const stderr = shim.getStderr().trim();
  if (stderr) console.error("[fetch_relay wasm stderr]", stderr);
  if (!stdout) throw new Error("WASM component produced no output");
  return JSON.parse(stdout);
}
